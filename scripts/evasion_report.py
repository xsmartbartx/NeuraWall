"""Run the evasion corpus against the Tier 2 detector and write docs/evasion-report.md.

uv run python scripts/evasion_report.py            # write the report
uv run python scripts/evasion_report.py --check    # exit 1 if the report is out of date
"""

# ruff: noqa: E501  (the report is prose)
from __future__ import annotations

import argparse
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from neurawall.core.models import FlowRecord, HttpMeta, L7Meta  # noqa: E402
from neurawall.modules.l7_classifier import L7Classifier  # noqa: E402
from neurawall.modules.l7_classifier.classifier import MODEL_VERSION  # noqa: E402
from tests.evasion_corpus import CASES, Case  # noqa: E402

OUT = ROOT / "docs" / "evasion-report.md"
FLOOR, ALERT = 0.3, 0.7


def measure(case: Case) -> tuple[str, float]:
    """Returns (outcome, confidence of the best finding with the expected label)."""
    try:
        flow = FlowRecord(
            src_ip="10.0.0.5",
            dst_ip="93.184.216.34",
            dst_port=443,
            l7=L7Meta(http=HttpMeta(method="GET", host="app.example.test", path=case.path)),
        )
    except ValueError:
        return "rejected", 0.0  # refused at ingest (e.g. a control character)
    best = max(
        (c.confidence for c in L7Classifier().classify(flow) if c.label == case.label), default=0.0
    )
    if best >= ALERT:
        return "alert", best
    if best >= FLOOR:
        return "caught", best
    return "missed", best


def render() -> str:
    rows = [(c, *measure(c)) for c in CASES]
    totals = Counter(outcome for _, outcome, _ in rows)
    by_class: dict[str, list] = defaultdict(list)
    for r in rows:
        by_class[r[0].klass].append(r)
    detected = totals["alert"] + totals["caught"]
    lines = [
        "# Tier 2 evasion report",
        "",
        f"Generated by `scripts/evasion_report.py` against `{MODEL_VERSION}`. Regenerate it after any detector change;",
        "`tests/unit/test_evasion_corpus.py` fails when a result here goes out of date.",
        "",
        "**What this is.** A measurement of one heuristic detector (SQL, command and template injection, path traversal and XSS in",
        "the request path and query) against well-known evasion techniques. It shows what the detector catches and what it misses.",
        "**What it is not.** A detection rate on real traffic, a benchmark against other products, or a statement about the DNS,",
        "beaconing, exfiltration and TLS detectors, which are stateful and are not covered here.",
        "",
        "Two thresholds: *caught* is a finding of at least 0.3 with the right label, the detector's floor. *Alert-grade* is at least 0.7,",
        "where the control plane raises an alert by itself without a matching rule. Remember that no detector can block: a rule",
        "a human approved is what enforces.",
        "",
        f"**{len(rows)} cases: {totals['alert']} alert-grade, {totals['caught']} caught below alert grade, {totals['missed']} missed"
        + (f", {totals['rejected']} refused at ingest" if totals["rejected"] else "")
        + f"** ({detected} of {len(rows)} detected).",
        "",
    ]
    below = [r for r in rows if r[1] == "caught"]
    lines += [
        "## Headline findings",
        "",
        f"- **Most single-rule hits are labelled but do not raise an alert.** {len(below)} of {len(rows)} cases landed between 0.3 and 0.7,",
        "  including the textbook `<script>alert(1)</script>` and a bare `|id`. The label is stored on the flow, but Tier 2 alone raises",
        "  an alert only at the bundle's classifier threshold (0.7 by default); a high Tier 1 anomaly score can still raise one.",
        "- **The starter rule that blocks web injection needs 0.9.** Only the payloads that trip two or more rules reach it, so the",
        "  baseline `UNION SELECT` (0.88) is alert-grade but is not blocked by the starter pack. Lowering the threshold trades missed",
        "  attacks for blocked legitimate requests; that choice belongs to the operator, which is why it is a rule a person approves.",
        f"- **{totals['missed']} cases are missed outright.** Mostly encodings and spellings the normaliser does not undo (versioned SQL",
        "  comments, full-width letters, HTML entities, wildcards and quote-splitting in shell words) and thresholds a lone weak rule does not reach.",
        "- **The detector is a first line, not a verdict.** NeuraWall's design assumes this: a model or heuristic can only raise an alert,",
        "  and a person approves any rule that blocks.",
        "",
    ]
    for klass, items in by_class.items():
        lines += [
            f"## {klass}",
            "",
            "| technique | request path | result | confidence | note |",
            "|---|---|---|---|---|",
        ]
        for case, outcome, conf in items:
            label = {
                "alert": "alert-grade",
                "caught": "caught",
                "missed": "**missed**",
                "rejected": "refused",
            }[outcome]
            path = case.path.replace("|", "\\|")
            lines.append(f"| {case.technique} | `{path}` | {label} | {conf:.2f} | {case.note} |")
        lines.append("")
    lines += ["## Known gaps, in plain words", ""]
    for case, outcome, _ in rows:
        if outcome == "missed":
            lines.append(f"- **{case.klass}, {case.technique}.** {case.note or 'Not recognised.'}")
    lines += [
        "",
        "These are heuristics, so every pattern has a bypass. That is why NeuraWall never lets a detector block on its own:",
        "a miss costs an alert you did not get, and a false positive costs nothing until a person approves a rule for it.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    text = render()
    if parser.parse_args().check:
        return 0 if OUT.exists() and OUT.read_text() == text else 1
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
